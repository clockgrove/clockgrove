import type { AssetManifest } from "@clockgrove/contracts";

const cell = (s: string): string => s.replaceAll("|", "\\|");

export function licenseReport(manifests: readonly AssetManifest[]): string {
  const sorted = [...manifests].sort((a, b) =>
    `${a.assetId}/${a.animationFamily}` < `${b.assetId}/${b.animationFamily}` ? -1 : 1,
  );
  const counts = new Map<string, number>();
  for (const m of sorted) counts.set(m.license, (counts.get(m.license) ?? 0) + 1);
  const summary = [...counts].sort().map(([license, n]) => `${license}: ${n}`);
  const credits = sorted.filter((m) => m.provenance.outputGrant?.attribution);
  return [
    "# Asset license report",
    "",
    "Generated by `pnpm --filter @clockgrove/assets run build`; do not edit.",
    "",
    "| Asset | Family | License | Creator | Tool | Source | Review | Reviewer | Content hash |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ...sorted.map(
      (m) =>
        `| ${[
          m.assetId,
          m.animationFamily,
          m.license,
          m.source.creator,
          m.source.tool ?? "-",
          m.source.kind,
          m.review.status,
          m.review.reviewer ?? "-",
          m.contentHash.slice(0, 12),
        ]
          .map(cell)
          .join(" | ")} |`,
    ),
    "",
    `Licenses: ${summary.length > 0 ? summary.join(", ") : "none"}`,
    ...(credits.length === 0
      ? []
      : [
          "",
          "## Provider credits",
          "",
          ...credits.map(
            (m) => `${m.assetId}/${m.animationFamily}: ${m.provenance.outputGrant?.attribution}`,
          ),
        ]),
    "",
  ].join("\n");
}
